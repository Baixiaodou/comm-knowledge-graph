"""路由判定 prompt（v2）：大小问题二分类判定规则，S2/S3/S4/S5 共用。

v1 教训：仅靠「有哪些/组成/内容」句式判大问题，会把「点名多个具体技术问分别/对比」
的具体知识点问题（载波同步、奈奎斯特准则…）误判为 hub。v2 增加核心判据：
**主语是否点名具体概念**——点名具体概念/定理/技术 → 小问题（LEAF），
主语是主题域/课程/模块全貌 → 大问题（HUB）。附正反例校准。
"""

ROUTE_SYSTEM = (
    "你是知识库检索路由。知识库是层级树：hub=枝干/大主题模块（一个主题域的总体/类型/"
    "构成/概览），core/leaf=具体知识点。严格按判定规则区分大问题与小问题，"
    "只输出 JSON，不要任何其他文字。"
)

RULE_BLOCK = """判定规则（大/小问题二分类）：
- 大问题（HUB）：主语是一个【主题域/课程/模块】（如：移动通信、通信原理、数字信号处理、随机信号处理、电磁场、计算机网络、数学、信道、调制、滤波器、采样、组网、检测与估计……），问的是这个域的整体全貌——"有哪些/包括什么/主要讲什么/有哪些类型/关键技术/方向"。
- 小问题（LEAF）：问题【点名了具体知识点/概念/定理/技术】并问其原理/区别/为什么/如何（如：载波同步、奈奎斯特准则、DSB-SC、升余弦、维纳-辛钦、QPSK、采样定理、匹配滤波、白噪声……）。即使句式开放（"分别解决什么问题""是什么关系"），只要主体是具体概念 → 小问题。
- 点名多个具体技术名并问"分别/关系/区别" → 小问题（具体知识点的对比或列举）。

示例：
- "移动通信都有哪些关键技术？" → 大问题（主语=移动通信 主题域全貌）
- "为什么 DSB-SC 不能用包络检波，而普通 AM 可以？" → 小问题（点名 DSB-SC/AM 具体概念）
- "载波同步、位同步、帧同步分别解决什么问题？" → 小问题（点名三个具体技术并问"分别"）
- "模拟调制都有哪些类型？" → 大问题（主语=模拟调制 主题域）
"""


def build_route_user(question: str, selection_part: str) -> str:
    return (
        f"用户问题：{question}\n\n"
        f"{RULE_BLOCK}"
        f"{selection_part}\n\n"
        '输出 JSON：{"path": "HUB"或"LEAF", "hubs": ["id1", "id2"（最多2个，无则空数组）], '
        '"reason": "一句话理由"}'
    )


def build_confirm_user(question: str, candidate_briefs: str) -> str:
    """S2 专用：只做二分类确认，不选点"""
    return (
        f"用户问题：{question}\n\n"
        f"{RULE_BLOCK}"
        f"候选主题域（hub）：\n{candidate_briefs}\n\n"
        "该问题是大问题（HUB）还是小问题（LEAF）？只输出 HUB 或 LEAF。"
    )
